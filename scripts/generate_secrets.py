#!/usr/bin/env python3
"""Generate a .env file with strong random values.

Refuses to overwrite an existing .env so an operator cannot accidentally
destroy the credentials of a running deployment. Use --force only when you
understand that a new database password on an existing volume prevents the API
from connecting.

Works on Windows, macOS and Linux: Python is already required for local backend
development, so it is the one interpreter we can rely on.
"""

from __future__ import annotations

import argparse
import secrets
import sys
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote

REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = REPO_ROOT / ".env"

TEMPLATE = """\
# Generated by scripts/generate_secrets.py on {timestamp}.
# Do not commit this file.
#
# Rotating POSTGRES_PASSWORD on an existing volume requires also changing the
# database role password; otherwise the API cannot connect. See README
# "配置与秘密" for the procedure.

POSTGRES_USER=acos
POSTGRES_PASSWORD={db_password}
POSTGRES_DB=acos
DATABASE_URL=postgresql+psycopg://acos:{db_password_encoded}@postgres:5432/acos

APP_ENV=production
APP_VERSION={app_version}
LOG_LEVEL=INFO
PUBLIC_BASE_URL={public_base_url}
EXTRA_ALLOWED_ORIGINS=[]

SESSION_TTL_HOURS={session_ttl_hours}
COOKIE_SECURE={cookie_secure}

PASSWORD_MIN_LENGTH=12
LOCKOUT_THRESHOLD=10
LOCKOUT_MINUTES=5

WEB_BIND_ADDRESS={web_bind_address}
WEB_PORT={web_port}

WORKER_NAME=worker-1
WORKER_HEARTBEAT_INTERVAL_SECONDS=5

ENABLE_API_DOCS=false
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate .env with random secrets")
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing .env (destroys current credentials)",
    )
    parser.add_argument("--port", default="8080", help="published web port (default 8080)")
    parser.add_argument("--bind", default="127.0.0.1", help="bind address (default loopback)")
    parser.add_argument(
        "--public-url",
        default=None,
        help="browser-facing base URL; defaults to http://localhost:<port>",
    )
    parser.add_argument(
        "--secure-cookie",
        action="store_true",
        help="mark cookies Secure (required when serving over HTTPS)",
    )
    parser.add_argument("--version", default="0.1.0", help="app version label")
    parser.add_argument("--session-hours", default="12", help="session lifetime in hours")
    args = parser.parse_args()

    if ENV_PATH.exists() and not args.force:
        print(
            "错误：.env 已存在。若确认要重新生成（会使现有数据库卷无法连接），"
            "请使用 --force。",
            file=sys.stderr,
        )
        return 1

    db_password = secrets.token_urlsafe(32)
    public_base_url = args.public_url or f"http://localhost:{args.port}"

    content = TEMPLATE.format(
        timestamp=datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        db_password=db_password,
        db_password_encoded=quote(db_password, safe=""),
        app_version=args.version,
        public_base_url=public_base_url,
        session_ttl_hours=args.session_hours,
        cookie_secure="true" if args.secure_cookie else "false",
        web_bind_address=args.bind,
        web_port=args.port,
    )

    ENV_PATH.write_text(content, encoding="utf-8")
    try:
        ENV_PATH.chmod(0o600)
    except OSError:
        pass  # Windows does not implement POSIX modes; ACLs apply instead.

    print(f"已生成 {ENV_PATH.name}。")
    print(f"PUBLIC_BASE_URL={public_base_url}")
    print(f"COOKIE_SECURE={'true' if args.secure_cookie else 'false'}")
    print("如通过 HTTPS 或其它域名访问，请修改 PUBLIC_BASE_URL 并把 COOKIE_SECURE 设为 true。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
